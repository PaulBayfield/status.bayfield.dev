export type Lang = "en" | "fr";
export type Translate = (key: StringKey, vars?: Record<string, string | number>) => string;

export function resolveLang(setting: "auto" | Lang): Lang {
  if (setting !== "auto") return setting;
  return navigator.language.toLowerCase().startsWith("fr") ? "fr" : "en";
}

export function makeT(lang: Lang): Translate {
  const strings: Record<StringKey, string> = lang === "fr" ? fr : en;
  return (key, vars) => (strings[key] ?? key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars?.[name] ?? `{${name}}`));
}

export type Formats = ReturnType<typeof makeFormats>;

export function makeFormats(lang: Lang) {
  const locale = lang === "fr" ? "fr-FR" : navigator.language.toLowerCase().startsWith("en") ? navigator.language : "en-GB";
  const mediumDate = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", year: "numeric" });
  const dateTime = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
  const time = new Intl.DateTimeFormat(locale, { hour: "2-digit", minute: "2-digit", second: "2-digit" });
  const timeWithDay = new Intl.DateTimeFormat(locale, { day: "numeric", month: "short", hour: "2-digit", minute: "2-digit" });
  const number = new Intl.NumberFormat(locale);

  return {
    locale,
    number: (n: number) => number.format(n),
    list: (items: string[]) => new Intl.ListFormat(locale, { type: "conjunction" }).format(items),
    mediumDate: (t: string | Date) => mediumDate.format(new Date(t)),
    dateTime: (t: string | Date) => dateTime.format(new Date(t)),
    /** "14:03:12" today, "2 Nov, 14:03" before. */
    time: (t: string | Date) => {
      const d = new Date(t);
      return d.toDateString() === new Date().toDateString() ? time.format(d) : timeWithDay.format(d);
    },
    /** "5 min ago", "3 days ago". */
    relative(t: string | Date, tr: Translate): string {
      const diff = (Date.now() - new Date(t).getTime()) / 1000;
      if (diff < 60) return tr("justNow");
      if (diff < 3600) return tr("minutesAgo", { n: Math.floor(diff / 60) });
      if (diff < 86400) return tr("hoursAgo", { n: Math.floor(diff / 3600) });
      if (diff < 30 * 86400) return tr("daysAgoRelative", { n: Math.floor(diff / 86400) });
      return mediumDate.format(new Date(t));
    },
  };
}
